#!/usr/bin/env python3
"""Read `terraform output -json waf_ingress_config` on stdin; edit dev WAF patch.

No AWS/terraform/kubectl commands, commits or pushes are executed by this script.
"""
import argparse
import json
from pathlib import Path
import re
import sys


def render(value):
    if not isinstance(value, dict) or value.get("environment") != "dev":
        raise ValueError("Expected the explicit dev WAF configuration")
    if "web_acl_arn" not in value:
        raise ValueError("Missing WAF ARN field")
    enabled, value = value.get("enabled"), value["web_acl_arn"]
    if enabled is False and value is None:
        arn = "none"
    elif enabled is True and isinstance(value, str) and re.fullmatch(
        r"arn:aws:wafv2:ap-northeast-2:[0-9]{12}:regional/webacl/"
        r"[A-Za-z0-9_-]+-dev-waf/[0-9a-fA-F-]{36}", value
    ):
        arn = value
    else:
        raise ValueError("Expected null or a Seoul REGIONAL WAFv2 Web ACL ARN")
    return (
        "# Generated by scripts/render-waf-ingress.py from Terraform output.\n"
        "apiVersion: networking.k8s.io/v1\nkind: Ingress\nmetadata:\n"
        "  name: main-ingress\n  namespace: app\n  annotations:\n"
        f"    alb.ingress.kubernetes.io/wafv2-acl-arn: {json.dumps(arn)}\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    try:
        patch = render(json.load(sys.stdin))
    except (ValueError, TypeError):
        sys.exit("Invalid WAF Terraform output; manifest left unchanged")
    args.output.write_text(patch)
    print(f"Updated WAF-only Ingress patch: {args.output}")


if __name__ == "__main__":
    main()
